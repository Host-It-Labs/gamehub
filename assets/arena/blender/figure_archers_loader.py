"""Private frozen loader; collector emits the installable reviewed entry.

Normal collector builds append the measured neutral copy without sculpting,
reducing or rebaking. Runtime blends and review gates stay in this figure's
owned work folder. The emitted normal builder uses the canonical runtime
cache and its fixed digest, so future builds do not depend on work galleries.
This module is not yet the shipped figure entry point.
"""
import importlib
import os
from pathlib import Path
import re

import bpy
import kit

R = Path(__file__).stem.split("_")[1]
gate = importlib.import_module("figure_" + R + "_gates")


def build(root_name=R):
    if root_name != R:
        raise ValueError("The frozen skeleton identity is fixed")
    version = gate.version_name(os.environ.get(R.upper() + "_REVIEW_VERSION", gate.VERSION))
    gate.require_review("source", version)
    gate.require_review("runtime", version)
    path = gate.artifact("runtime", version)
    existing = set(bpy.data.materials)
    with bpy.data.libraries.load(str(path), link=False) as (source, loaded):
        loaded.objects = list(source.objects)
    for obj in loaded.objects:
        if obj is not None:
            bpy.context.collection.objects.link(obj)
    root = next(obj for obj in loaded.objects if obj and obj.name == R)
    if len(kit.descendants(root)) != len([o for o in loaded.objects if o is not None]):
        raise RuntimeError("Frozen file contains objects outside its figure")
    for key, value in gate.fingerprints().items():
        if root.get(key) != value:
            raise RuntimeError("Frozen runtime provenance changed: " + key)
    for obj in kit.descendants(root):
        if obj.type != "MESH":
            continue
        for slot in obj.material_slots:
            material = slot.material
            if material is None:
                continue
            base = re.sub(r"(?:\.\d{3})+$", "", material.name)
            if base != material.name:
                shared = bpy.data.materials.get(base)
                if shared is not None:
                    slot.material = shared
                else:
                    material.name = base
    for material in list(bpy.data.materials):
        if material not in existing and material.users == 0 and re.search(r"\.\d{3}$", material.name):
            bpy.data.materials.remove(material)
    root["runtimeCopySource"] = str(path.relative_to(gate.PROJECT))
    root["arenaReviewedAO"] = True
    kit.refresh()
    return root


