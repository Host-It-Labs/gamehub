def bow_string(armature):
    # Only endpoint rings: the rendered line between them remains straight
    # under skinning. No intermediate linearly blended vertices can drift.
    centre=BRACE;parts=[]
    for sign,suffix in ((1,"L"),(-1,"R")):
        tip=GRIP_L+BOW_UP*(sign*(.56-.003))-BOW_FWD*.121
        obj=geo.tube(R+f".linen-string{suffix}",[tip,centre],[.0012,.0012],STRING,n=8,up=BOW_FWD,caps=("flat","flat"))
        distance=np.array([(v.co-centre).length for v in obj.data.vertices])
        # tube has two rings only, plus flat n-gon end caps; no dome.
        end=distance<.0025
        weight(obj,armature,{"wing"+suffix:1-end.astype(float),"extra2":end.astype(float)})
        tag(obj,40,"endpoint-weighted linen bowstring");parts.append(obj)
    return parts


