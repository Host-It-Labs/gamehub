def weight_coat(obj,armature,arms=True):
    p=np.array([v.co[:] for v in obj.data.vertices]);x,y,z=p.T
    upper=soft(.769,.904,z);values={"torso":1-upper,"chest":upper}
    width=np.interp(z,[r[0] for r in BODY],[r[1] for r in BODY])
