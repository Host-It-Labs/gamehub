def shoulder_roof(x,y,base):
    # Conservative rounded sleeve-head envelope. The cape follows this
    # roof with actual clearance rather than cutting a cone through it.
    roof=base
    for sign in (-1,1):
        ellipsoid=((x-sign*.200)/.074)**2+((y+.004)/.070)**2
        if ellipsoid<1.75:
            # Continue the outer shoulder into its hanging cloth. An abrupt
            # cutoff at the ellipsoid boundary would make a new sharp ridge.
            coverage=float(soft(1.75,.75,ellipsoid))
            top=.939+.053*math.exp(-ellipsoid*1.3)+.010
            roof=max(roof,base+(top-base)*coverage)
    return roof


def cape_point(a,t):
    r=CAPE_INNER+CAPE_SPAN*t
    x,y=math.sin(a)*r,math.cos(a)*r*CAPE_Y
    z=1.032-.171*t
    shoulder=shoulder_roof(x,y,z)
    # The rounded shoulder crest ends before the outer hem. Its weight
    # fades into a hanging leaf, so the sides cannot finish as raised tips.
    roof=z+(shoulder-z)*float(soft(1,.85,t))
    if roof>z:
        # Smooth maximum rounds the join between chest drape and shoulder.
        desired=roof
        z=.5*(z+desired+math.sqrt((z-desired)**2+.004**2))
    # The inner shoulder bridges over the clavicle before it reaches the
    # sleeve-head crest; wool thickness clears both connected surfaces.
    z+=.006*g(t,.35,.20)*abs(math.sin(a))**4
    z+=.0030*math.cos(a*6+.5)*math.sin(math.pi*t)**2
    # A gently scalloped hanging hem. It never changes the shoulder crest.
    z+=.0020*math.cos(a*4)*t**6
    return V(x,y,z)


