def hood_point(a,t):
    # Explicit outside-skull waypoints replace the old quadratic's inward
    # swing through the temples. The face opening, outer crown and neck
    # ring each have a deliberate envelope and bounded interpolation.
    cs,sn=math.cos(a),math.sin(a)
    opening=hood_opening(a)
    crown=V(.108*sn,-.102*cs-.041*(1-abs(cs)),
            1.151+.175*max(0,cs)-.145*max(0,-cs))
    neck=V(.066*sn,-.078*cs,1.007-.004*cs)
    xyz=profile([(0,*opening),(.33,*crown),(1,*neck)],t)
    p=V(xyz)
    # Broad folds only on the rear/side fabric, with a protected opening.
    p.x+=sn*.0021*math.cos(a*4+t*2)*math.sin(math.pi*t)**2
    p.y-=.0022*math.cos(a*3-t*3)*math.sin(math.pi*t)**2
    return p


