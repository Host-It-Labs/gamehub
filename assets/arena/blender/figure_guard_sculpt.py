def body_point(a,z,lift=0):
    w,f,b=profile(BODY,z);sn,cs=math.sin(a),math.cos(a)
    x=math.copysign(abs(sn)**.86,sn)*(w+lift)
    y=math.copysign(abs(cs)**.88,cs)*((f if cs>0 else b)+lift)
    ad=abs((math.degrees(a)+180)%360-180)
    y+=cs*(.0016*math.cos(a*36)*g(z,.8,.22)+.0026*math.sin(a*5+z*17)*g(z,.675,.031))
    if ad<90:
        y+=.010*g(ad,31,22)*g(z,.887,.047)
        y-=.0035*g(ad,0,9)*g(z,.89,.076)
    else:
        y-=.006*g(ad,148,21)*g(z,.919,.046)
        y+=.0025*g(ad,180,8)*g(z,.877,.08)
    y+=cs*fold_relief(z,a,.731,.019,.009,.0038,.6)*g(ad,53,28)
    return V(x,y,z)


